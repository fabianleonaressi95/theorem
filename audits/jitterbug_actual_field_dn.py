"""Actual Jitterbug-panel flux, finite source coil, and receiver energy audit.

The eight receiver coils follow the Gray/Jitterbug panel poses. External field
is generated by a fixed-current circular source winding; its Biot-Savart field
is integrated over each finite receiver disk. This is a numerical engineering
model, not a measured apparatus or a complete primary-source/mechanical model.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from audits.jitterbug_gray_kinematics import (
    cuboctahedron, tetrahedral_group, orbit_data, jitterbug_path,
    configs, rigid_triangles,
)
from audits.jitterbug_eight_coil_coupling import (
    MU0, coil_polygon, panel_frames, neumann_mutual,
    midpoint_coupled_rl,
)


def circular_source_segments(radius, center, normal, segments):
    n = np.asarray(normal, float)
    n /= np.linalg.norm(n)
    trial = np.array([1.0, 0.0, 0.0])
    if abs(np.dot(trial, n)) > 0.9:
        trial = np.array([0.0, 1.0, 0.0])
    u = np.cross(n, trial)
    u /= np.linalg.norm(u)
    v = np.cross(n, u)
    theta = 2*np.pi*np.arange(segments)/segments
    points = np.asarray(center) + radius*(np.cos(theta)[:, None]*u +
                                          np.sin(theta)[:, None]*v)
    dl = np.roll(points, -1, axis=0) - points
    return points, dl


def biot_savart_polygon(points, source_points, source_dl, current):
    """B at arbitrary points from a polygonal filament, midpoint segment rule."""
    p = np.asarray(points, float).reshape(-1, 3)
    mid = source_points + 0.5*source_dl
    r = p[:, None, :] - mid[None, :, :]
    r2 = np.sum(r*r, axis=2)
    if np.any(r2 < 1e-18):
        raise ValueError("field quadrature intersects the source filament")
    cross = np.cross(source_dl[None, :, :], r)
    B = (MU0*current/(4*np.pi))*np.sum(
        cross/(r2[:, :, None]**1.5), axis=1)
    return B.reshape(np.asarray(points).shape)


def disk_quadrature(center, rotation, normal0, radius, nr=6, ntheta=24):
    """Midpoint polar quadrature on a finite circular coil surface."""
    n0 = np.asarray(normal0, float)
    n0 /= np.linalg.norm(n0)
    trial = np.array([1., 0., 0.])
    if abs(np.dot(trial, n0)) > 0.9:
        trial = np.array([0., 1., 0.])
    u0 = np.cross(n0, trial)
    u0 /= np.linalg.norm(u0)
    v0 = np.cross(n0, u0)
    u, v, n = rotation @ u0, rotation @ v0, rotation @ n0
    rr = radius*np.sqrt((np.arange(nr)+0.5)/nr)
    tt = 2*np.pi*(np.arange(ntheta)+0.5)/ntheta
    points = np.array([center + r*(np.cos(t)*u + np.sin(t)*v)
                       for r in rr for t in tt])
    weights = np.full(len(points), np.pi*radius**2/len(points))
    return points, n, weights


def finite_surface_flux(center, rotation, normal0, radius, turns,
                        source_points, source_dl, source_current,
                        nr=6, ntheta=24):
    points, normal, weights = disk_quadrature(
        center, rotation, normal0, radius, nr, ntheta)
    field = biot_savart_polygon(points, source_points, source_dl,
                                source_current)
    return float(turns*np.sum((field @ normal)*weights))


def build_actual_mechanism_run(
    edge_length_m=0.1, speed_m_s=0.01, turns=100,
    radius_fraction=0.65, wire_radius_m=1e-4, resistance_ohm=10.0,
    ds=0.08, segments=48, softening_m=1e-5,
    source_radius_m=0.20, source_turns=500, source_current_A=1.0,
    source_segments=256, disk_nr=6, disk_ntheta=24,
):
    """Use the actual Gray path and panel poses; no prescribed angular law."""
    V0 = cuboctahedron()
    T = tetrahedral_group()
    A, Qs = orbit_data(V0, T)
    path = jitterbug_path(V0, A, Qs, ds=ds)
    Wcfg = configs(path, A)*edge_length_m
    tris = rigid_triangles(V0)
    labels = list(tris.keys())
    rotations, centers, normals, fit_residuals = [], [], [], []
    for label in labels:
        R, c, n0, residual = panel_frames(Wcfg, V0, tris[label])
        rotations.append(R)
        centers.append(c)
        normals.append(n0)
        fit_residuals.append(residual)
    rotations = np.stack(rotations, axis=1)
    centers = np.stack(centers, axis=1)
    normals = np.asarray(normals)
    fit_residuals = np.stack(fit_residuals, axis=1)

    frame_times = np.concatenate([[0.0], np.cumsum(
        np.linalg.norm(np.diff(path, axis=0), axis=1)*edge_length_m/speed_m_s
    )])
    radius = radius_fraction*(edge_length_m/(2*np.sqrt(3)))
    if not (0 < radius < edge_length_m/(2*np.sqrt(3))):
        raise ValueError("invalid receiver coil radius")
    source_pts, source_dl = circular_source_segments(
        source_radius_m, np.zeros(3), np.array([0., 0., 1.]),
        source_segments)

    nframes = len(frame_times)
    ncoils = 8
    flux = np.zeros((nframes, ncoils))
    Lseq = np.zeros((nframes, ncoils, ncoils))
    N = [int(turns)]*ncoils
    radii = [radius]*ncoils
    wires = [wire_radius_m]*ncoils
    for k in range(nframes):
        loops = []
        for j in range(ncoils):
            loops.append(coil_polygon(centers[k, j], rotations[k, j],
                                      normals[j], radius, segments))
            flux[k, j] = finite_surface_flux(
                centers[k, j], rotations[k, j], normals[j], radius, turns,
                source_pts, source_dl, source_current_A, disk_nr, disk_ntheta)
        # Use one common finite-core Green kernel for every diagonal and
        # off-diagonal entry. Mixing thin-wire self terms with separately
        # softened mutual terms can destroy positive semidefiniteness.
        L = np.zeros((ncoils, ncoils))
        for i in range(ncoils):
            L[i, i] = neumann_mutual(
                loops[i], loops[i], N[i], N[i], wire_radius_m)
            for j in range(i):
                mij = neumann_mutual(
                    loops[i], loops[j], N[i], N[j], wire_radius_m)
                L[i, j] = L[j, i] = mij
        Lseq[k] = L

    emf = -np.diff(flux, axis=0)/np.diff(frame_times)[:, None]
    Rmat = np.eye(ncoils)*resistance_ohm
    currents = midpoint_coupled_rl(Lseq, emf, frame_times, Rmat)

    # Exact discrete receiver-side energy identity for the midpoint scheme:
    # Ein = Delta magnetic energy + Joule heat + mechanical transfer term.
    Ein = joule = mechanical = delta_magnetic = 0.0
    energy_rows = []
    for k, dt in enumerate(np.diff(frame_times)):
        i0, i1 = currents[k], currents[k+1]
        im = 0.5*(i0+i1)
        L0, L1 = Lseq[k], Lseq[k+1]
        dL = L1-L0
        e_mid = emf[k]
        p_in = float(im @ e_mid)
        p_j = float(im @ Rmat @ im)
        p_mech = float(0.5*im @ dL @ im / dt)
        W0 = float(0.5*i0 @ L0 @ i0)
        W1 = float(0.5*i1 @ L1 @ i1)
        dW = W1-W0
        Ein += p_in*dt
        joule += p_j*dt
        mechanical += p_mech*dt
        delta_magnetic += dW
        energy_rows.append({
            "time_mid_s": float(0.5*(frame_times[k]+frame_times[k+1])),
            "electrical_input_W": p_in,
            "joule_loss_W": p_j,
            "receiver_mechanical_transfer_W": p_mech,
            "magnetic_energy_change_W": dW/dt,
        })
    residual = Ein-delta_magnetic-joule-mechanical
    scale = max(abs(Ein), abs(delta_magnetic)+joule+abs(mechanical), 1e-30)

    return {
        "model": "eight receiver coils rigidly attached to the actual Gray/Jitterbug triangular panels",
        "status": "finite-surface Biot-Savart excitation and receiver-side discrete energy audit; not measured hardware",
        "kinematics": "jitterbug_path -> configs -> rigid_triangles -> Kabsch panel_frames",
        "source": {
            "geometry": "fixed circular filament winding centered at origin in the xy-plane",
            "radius_m": source_radius_m, "turns": source_turns,
            "current_A": source_current_A, "segments": source_segments,
            "field_model": "polygonal Biot-Savart midpoint quadrature",
        },
        "receiver": {
            "count": ncoils, "turns_each": turns, "radius_m": radius,
            "wire_radius_m": wire_radius_m, "resistance_ohm_each": resistance_ohm,
            "loop_segments": segments,
            "surface_quadrature": {"radial": disk_nr, "angular": disk_ntheta},
        },
        "frames": nframes, "duration_s": float(frame_times[-1]),
        "max_panel_fit_residual_m": float(np.max(fit_residuals)),
        "max_abs_flux_linkage_Wb_turn": float(np.max(np.abs(flux))),
        "max_abs_external_emf_V": float(np.max(np.abs(emf))),
        "max_abs_current_A": float(np.max(np.abs(currents))),
        "min_inductance_eigenvalue_H": float(min(
            np.linalg.eigvalsh(L).min() for L in Lseq)),
        "max_inductance_reciprocity_residual_H": float(np.max(
            np.abs(Lseq-np.swapaxes(Lseq, 1, 2)))),
        "energy_audit_receiver_side_J": {
            "electrical_port_input": Ein,
            "magnetic_energy_change": delta_magnetic,
            "joule_dissipation": joule,
            "mechanical_transfer_from_variable_L": mechanical,
            "balance_residual": residual,
            "relative_balance_residual": abs(residual)/scale,
            "scope": "receiver circuit identity only; primary-source supply and actuator dynamics are not yet modeled",
        },
        "energy_time_series": energy_rows,
        "flux_linkage_Wb_turn": flux.tolist(),
        "external_emf_V": emf.tolist(),
        "currents_A": currents.tolist(),
        "times_s": frame_times.tolist(),
    }


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--output", type=Path, default=None)
    p.add_argument("--ds", type=float, default=0.08)
    p.add_argument("--segments", type=int, default=48)
    p.add_argument("--source-current-A", type=float, default=1.0)
    p.add_argument("--source-radius-m", type=float, default=0.20)
    args = p.parse_args()
    report = build_actual_mechanism_run(
        ds=args.ds, segments=args.segments,
        source_current_A=args.source_current_A,
        source_radius_m=args.source_radius_m)
    rendered = json.dumps(report, indent=2)
    if args.output:
        args.output.write_text(rendered+"\n", encoding="utf-8")
    print(rendered)


if __name__ == "__main__":
    main()
