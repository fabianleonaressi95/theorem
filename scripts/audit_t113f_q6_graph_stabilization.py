#!/usr/bin/env python3
"""Derive the T2u stabilization threshold from the canonical Q6 edge energy.

The Q6 Dirichlet term is an explicit constitutive hypothesis:
E_Q6[u] = kappa/2 sum_{<v,w> in E(Q6)} |u_v-u_w|^2.
No scalar shift is inserted by hand. The induced 3x3 matrix on the
existing RGS T2u triplet is computed from the actual Q6 incidence/Laplacian.
"""
from __future__ import annotations
import json
from pathlib import Path
import numpy as np
from scipy.linalg import eigh
from models.tangent_triplet_anisotropy import reconstruct_rgs_t2u_triplet


def q6_laplacian():
    A = np.zeros((64, 64), dtype=float)
    for v in range(64):
        for bit in range(6):
            A[v, v ^ (1 << bit)] = 1.0
    return 6.0 * np.eye(64) - A


def audit(source="data/rgs_188d/X_Oh_reconstructed.csv"):
    root = Path(__file__).resolve().parents[1]
    data = np.genfromtxt(root / source, delimiter=",", names=True)
    X = np.column_stack([data[k] for k in ("x", "y", "z")])
    rec = reconstruct_rgs_t2u_triplet(X)
    V, Q, Kc = rec["basis"], rec["source_tangent_basis"], rec["constrained_coulomb_hessian"]
    L = q6_laplacian()
    # Edge Dirichlet Hessian on 192 Cartesian displacement coordinates.
    Kq_full = np.kron(L, np.eye(3))
    Kq = Q.T @ Kq_full @ Q
    Mq = V.T @ Kq @ V
    Mq = 0.5 * (Mq + Mq.T)
    Kt = V.T @ Kc @ V
    Kt = 0.5 * (Kt + Kt.T)
    lam = np.linalg.eigvalsh(Kt)
    qev = np.linalg.eigvalsh(Mq)
    if qev[0] <= 1e-12:
        threshold = None
        stable = False
        reason = "Q6 edge form is not positive definite on this triplet"
    else:
        # Generalized eigenvalues Kt x = -kappa Mq x.
        criticals = eigh(-Kt, Mq, eigvals_only=True)
        threshold = float(np.max(criticals))
        stable = bool(threshold >= 0.0)
        reason = "strict stability for kappa > max eig(-Kt,Mq)"
    # Check the full constrained action, not just a fitted scalar correction.
    result = {
        "schema": "t113f-q6-graph-elastic-stabilization/v1",
        "constitutive_term": "kappa/2 * sum_{Q6 edges} ||u_v-u_w||^2",
        "q6_vertices": 64, "q6_edges": 192, "q6_degree": 6,
        "t2u_triplet_eigenvalues_coulomb": lam.tolist(),
        "q6_dirichlet_restricted_matrix": Mq.tolist(),
        "q6_dirichlet_eigenvalues_on_triplet": qev.tolist(),
        "critical_kappa": threshold,
        "strictly_stable_for_kappa_greater_than_critical": stable,
        "criterion": reason,
        "stiffness_at_kappa": "Kt + kappa*Mq",
        "source_triplet_diagnostics": rec["diagnostics"],
        "interpretation": (
            "This computes the threshold generated by the canonical Q6 edge "
            "Dirichlet form. Kappa remains a constitutive coupling to be fixed "
            "by a microscopic action or measurement; it is not fitted to force "
            "stability. The result is a harmonic stability test, not a phason "
            "identification or a continuum phonon dispersion."
        ),
    }
    return result


if __name__ == "__main__":
    print(json.dumps(audit(), indent=2, sort_keys=True))
