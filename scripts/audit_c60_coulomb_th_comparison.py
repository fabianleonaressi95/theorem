#!/usr/bin/env python3
"""Ideal C60 truncated-icosahedron Coulomb Hessian and T_h comparison with Q6-64.

C60 is generated by directed-edge truncation (2u+v)/3 of a regular
icosahedron. The operator is the all-pairs 1/r Hessian. This is an ideal
polyhedral model, not an optimized molecular/DFT geometry.
"""
from __future__ import annotations
import argparse, itertools, json
from pathlib import Path
import numpy as np
from scipy.spatial import ConvexHull
from scipy.spatial.distance import cdist
from scipy.linalg import null_space

TOL=1e-8
OMEGA=np.exp(2j*np.pi/3)
CHARS={
 '1':{'E':1,'C3a':1,'C3b':1,'C2':1},
 '1p':{'E':1,'C3a':OMEGA,'C3b':OMEGA**2,'C2':1},
 '1pp':{'E':1,'C3a':OMEGA**2,'C3b':OMEGA,'C2':1},
 '3':{'E':3,'C3a':0,'C3b':0,'C2':-1}}

def icosahedron():
    ph=(1+np.sqrt(5))/2
    p=[]
    for s,t in itertools.product((-1,1),repeat=2): p.append((0,s,t*ph))
    for s,t in itertools.product((-1,1),repeat=2): p.append((s,t*ph,0))
    for s,t in itertools.product((-1,1),repeat=2): p.append((t*ph,0,s))
    return np.asarray(p,float)

def make_c60():
    ico=icosahedron(); hull=ConvexHull(ico)
    edges=sorted({tuple(sorted((int(i),int(j)))) for tri in hull.simplices
                  for i,j in itertools.combinations(tri,2)})
    if len(edges)!=30: raise RuntimeError(f'Expected 30 icosahedron edges, got {len(edges)}')
    C=[]
    for i,j in edges:
        C.extend(((2*ico[i]+ico[j])/3,(2*ico[j]+ico[i])/3))
    C=np.asarray(C,float); D=cdist(C,C)
    adj=(D>1e-9)&(np.abs(D-2/3)<1e-8)
    if C.shape!=(60,3) or adj.sum()//2!=90 or not np.all(adj.sum(1)==3):
        raise RuntimeError('Truncated-icosahedron validation failed')
    if np.ptp(np.linalg.norm(C,axis=1))>1e-8: raise RuntimeError('C60 not spherical')
    return ico,C,adj

def frame(a,b):
    e1=a/np.linalg.norm(a); v=b-e1*np.dot(e1,b); e2=v/np.linalg.norm(v)
    return np.column_stack((e1,e2,np.cross(e1,e2)))

def rotations(ico):
    D=cdist(ico,ico); nb=[np.where(np.abs(D[i]-2)<1e-8)[0].tolist() for i in range(12)]
    B0=frame(ico[0],ico[nb[0][0]]); out=[]
    for k in range(12):
        for ell in nb[k]:
            R=frame(ico[k],ico[ell])@B0.T
            Dm=cdist(ico@R.T,ico); p=Dm.argmin(1)
            if Dm[np.arange(12),p].max()<TOL and len(set(p.tolist()))==12:
                if not any(np.linalg.norm(R-S)<1e-8 for S in out): out.append(R)
    if len(out)!=60: raise RuntimeError(f'Expected 60 proper Ih rotations, got {len(out)}')
    return out

def group_data(Rs):
    def idx(M):
        ds=[np.linalg.norm(M-R) for R in Rs]; k=int(np.argmin(ds))
        if ds[k]>1e-7: raise RuntimeError('Ih multiplication not closed')
        return k
    mult=np.asarray([[idx(A@B) for B in Rs] for A in Rs],int); e=idx(np.eye(3))
    order=[]
    for i in range(60):
        x=e
        for n in range(1,7):
            x=mult[x,i]
            if x==e: break
        order.append(n)
    inv=np.asarray([next(j for j in range(60) if mult[i,j]==e and mult[j,i]==e) for i in range(60)])
    return mult,e,order,inv

def subgroup(gens,mult,e):
    S={e}; stack=[e]
    while stack:
        x=stack.pop()
        for g in gens:
            y=int(mult[x,g])
            if y not in S: S.add(y); stack.append(y)
    return S

def find_th(mult,e,orders,inv):
    o3=[i for i,o in enumerate(orders) if o==3]; chosen=None
    for a in o3:
        for b in o3:
            if a>=b: continue
            S=subgroup((a,b),mult,e)
            if len(S)==12: chosen=S; break
        if chosen: break
    if chosen is None: raise RuntimeError('No A4 subgroup found')
    classes=[]; unseen=set(chosen)
    while unseen:
        g=min(unseen)
        cl={int(mult[mult[x,g],inv[x]]) for x in chosen}
        classes.append(cl); unseen-=cl
    if sorted(map(len,classes))!=[1,3,4,4]: raise RuntimeError('A4 classes invalid')
    c3=sorted((c for c in classes if len(c)==4),key=min); cls={}
    for c in classes:
        name='E' if len(c)==1 else ('C2' if len(c)==3 else ('C3a' if c==c3[0] else 'C3b'))
        for g in c: cls[int(g)]=name
    return sorted(chosen),cls

def coulomb(X):
    n=len(X); g=np.zeros((n,3)); H=np.zeros((3*n,3*n)); E=0.
    for i in range(n):
        for j in range(i+1,n):
            d=X[i]-X[j]; r=np.linalg.norm(d); E+=1/r
            g[i]+=-d/r**3; g[j]+=d/r**3
            B=3*np.outer(d,d)/r**5-np.eye(3)/r**3
            si=slice(3*i,3*i+3); sj=slice(3*j,3*j+3)
            H[si,si]+=B; H[sj,sj]+=B; H[si,sj]-=B; H[sj,si]-=B
    return E,g,H

def tangent(X):
    n=len(X); x=X.reshape(-1)
    N=np.column_stack([np.tile(np.eye(3)[k],n) for k in range(3)]+[x])
    return null_space(N.T)

def action(X,M):
    n=len(X); D=cdist(X@M.T,X); p=D.argmin(1); err=float(D[np.arange(n),p].max())
    if err>TOL or len(set(p.tolist()))!=n: raise RuntimeError('Invalid point action')
    S=np.zeros((3*n,3*n))
    for i,j in enumerate(p): S[3*j:3*j+3,3*i:3*i+3]=M
    return p,S,err

def c60_actions(C,Rs,ids,cls,Q):
    th=[]; full=[]
    for rid,R in enumerate(Rs):
        for parity in (1,-1):
            M=parity*R; p,S,err=action(C,M); U=Q.T@S@Q
            a={'M':M,'p':p,'S':S,'U':U,'parity':parity,'rid':rid,'error':err}
            full.append(a)
            if rid in ids: a['class']=cls[rid]; th.append(a)
    if len(th)!=24 or len(full)!=120: raise RuntimeError('Incorrect Ih/T_h orders')
    return th,full

def signed_class(R):
    if np.allclose(R,np.eye(3)): return 'E'
    if round(float(np.trace(R)))==-1: return 'C2'
    p=tuple(np.argmax(np.abs(R),axis=1).tolist())
    return 'C3a' if p==(1,2,0) else 'C3b'

def q6_actions(X,Q):
    out=[]
    for perm in itertools.permutations(range(3)):
        P=np.eye(3)[list(perm)]
        for signs in itertools.product((-1,1),repeat=3):
            G=np.diag(signs)@P; det=int(round(np.linalg.det(G)))
            if int(round(np.prod(G[np.abs(G)>0.5])))!=det: continue
            p,S,err=action(X,G); U=Q.T@S@Q
            out.append({'G':G,'U':U,'parity':det,'class':signed_class(det*G),'error':err})
    if len(out)!=24: raise RuntimeError(f'Q6 T_h order {len(out)}, expected 24')
    return out

def blocks(acts,K,n):
    out={}
    for par in ('g','u'):
        for ir in ('1','1p','1pp','3'):
            d=3 if ir=='3' else 1; P=np.zeros((n,n),complex)
            for a in acts:
                chi=CHARS[ir][a['class']]*(1 if par=='g' else a['parity'])
                P+=np.conjugate(chi)*a['U']
            P*=d/24; P=(P+P.conj().T)/2
            ev,V=np.linalg.eigh(P); B=V[:,ev>0.5]
            w=np.linalg.eigvalsh(B.conj().T@K@B)
            if len(w)%d: raise RuntimeError('Non-integral irrep multiplicity')
            out[ir+par]={'rank':int(len(w)),'multiplicity':int(len(w)//d),
                'min':float(w.min()),'max':float(w.max()),'mean':float(w.mean()),
                'std':float(w.std()),'negative':int(np.sum(w<-1e-8)),
                'near_zero':int(np.sum(np.abs(w)<=1e-8)),'positive':int(np.sum(w>1e-8)),
                'projector_idempotence_fro':float(np.linalg.norm(P@P-P,'fro')),
                'projector_commutator_fro':float(np.linalg.norm(P@K-K@P,'fro'))}
    return out

def normalized(b,rms):
    f=rms**3
    return {k:{a:(v*f if a in ('min','max','mean','std') else v) for a,v in x.items()} for k,x in b.items()}

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--npz',required=True); ap.add_argument('--out-dir',default='c60_coulomb_th_audit')
    a=ap.parse_args(); out=Path(a.out_dir); out.mkdir(parents=True,exist_ok=True)
    z=np.load(a.npz); X64=z['X_Oh_reconstructed']; Q64=z['Q_tangent']
    E64,g64,H64=coulomb(X64); K64=Q64.T@H64@Q64; K64=(K64+K64.T)/2
    acts64=q6_actions(X64,Q64); r64=float(np.sqrt(np.mean(np.sum(X64**2,axis=1))))
    b64=normalized(blocks(acts64,K64,188),r64)
    ico,C,adj=make_c60(); Rs=rotations(ico); mult,e,orders,inv=group_data(Rs)
    ids,cls=find_th(mult,e,orders,inv); Q=tangent(C)
    E,g,H=coulomb(C); x=C.reshape(-1); gv=g.reshape(-1)
    lam=-float(gv@x)/float(x@x); residual=gv+lam*x
    K=Q.T@H@Q; K=(K+K.T)/2; w=np.linalg.eigvalsh(K)
    acts,full=c60_actions(C,Rs,set(ids),cls,Q)
    r60=float(np.sqrt(np.mean(np.sum(C*C,axis=1))))
    b60=normalized(blocks(acts,K,176),r60)
    cfull=max(float(np.linalg.norm(K@a['U']-a['U']@K,'fro')/np.linalg.norm(K,'fro')) for a in full)
    cth=max(float(np.linalg.norm(K@a['U']-a['U']@K,'fro')/np.linalg.norm(K,'fro')) for a in acts)
    c64=max(float(np.linalg.norm(K64@a['U']-a['U']@K64,'fro')/np.linalg.norm(K64,'fro')) for a in acts64)
    cmp={}
    for k in b64:
        cmp[k]={'Q6_64':b64[k],'C60_ideal':b60[k],
          'multiplicity_difference_C60_minus_Q6':b60[k]['multiplicity']-b64[k]['multiplicity'],
          'normalized_min_difference':b60[k]['min']-b64[k]['min'],
          'normalized_max_difference':b60[k]['max']-b64[k]['max'],
          'normalized_mean_difference':b60[k]['mean']-b64[k]['mean']}
    report={
      'geometry':{'construction':'directed-edge truncation (2u+v)/3 of regular icosahedron',
        'vertices':60,'icosahedron_edges':30,'C60_bonds':int(adj.sum()//2),
        'degree_min':int(adj.sum(1).min()),'degree_max':int(adj.sum(1).max()),
        'bond_length_min':float(cdist(C,C)[adj].min()),'bond_length_max':float(cdist(C,C)[adj].max()),
        'radius_min':float(np.linalg.norm(C,axis=1).min()),'radius_max':float(np.linalg.norm(C,axis=1).max()),
        'rms_radius':r60,'warning':'Ideal exact polyhedron, not optimized molecular/DFT C60.'},
      'tangent_space':{'ambient_dimension':180,'removed_normals':'3 translations + 1 global dilation',
        'dimension':176,'Q_orthogonality_fro':float(np.linalg.norm(Q.T@Q-np.eye(176),'fro')),
        'max_action_subspace_residual':max(float(np.linalg.norm(a['S']@Q-Q@a['U'],'fro')) for a in acts)},
      'C60_coulomb':{'energy':E,'gradient_norm':float(np.linalg.norm(gv)),
        'gradient_tangent_norm':float(np.linalg.norm(Q.T@gv)),
        'radial_multiplier_least_squares':lam,'residual_after_radial_multiplier':float(np.linalg.norm(residual)),
        'radial_alignment_cosine':float(abs(gv@x)/(np.linalg.norm(gv)*np.linalg.norm(x))),
        'translation_force_norm':float(np.linalg.norm(g.sum(0))),
        'projected_raw_Hessian_spectrum':{'min':float(w.min()),'max':float(w.max()),
          'negative':int(np.sum(w<-1e-8)),'near_zero':int(np.sum(np.abs(w)<=1e-8)),
          'positive':int(np.sum(w>1e-8))},
        'classification':'not stationary on translation/scale-reduced sphere tangent; projected Hessian diagnostic only'},
      'symmetry':{'proper_icosahedral_rotations':60,'full_Ih_order':120,'T_h_order':24,
        'max_relative_commutator_full_Ih':cfull,'max_relative_commutator_T_h_C60':cth,
        'max_relative_commutator_T_h_Q6_64':c64},
      'normalization':{'rule':'multiply eigenvalues by RMS_radius^3 (both configurations rescaled to RMS radius 1)',
        'Q6_64_rms_radius':r64,'C60_rms_radius':r60,
        'both_raw_projected_Hessians_used':True,'Lagrange_shift_applied':False},
      'T_h_sector_comparison':cmp,
      'classification':{'C60_geometry':'ideal truncated icosahedron','C60_T_h_equivariance':'verified numerically',
        'C60_Coulomb_stationarity':'fails','comparison':'T_h isotypic spectra compared after common RMS scaling; no mode-by-mode pairing',
        '64_to_60_bijection':'not assumed'}}
    np.savez_compressed(out/'C60_Coulomb_T_h.npz',X_C60=C,Q_tangent=Q,H_Coulomb=H,
      K_Coulomb_projected=K,gradient=g,K_Q6_64_raw_projected=K64,
      eigenvalues_C60=w,lambda_radial_least_squares=np.array(lam),bond_adjacency=adj)
    (out/'report.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps(report,indent=2))

if __name__=='__main__': main()
