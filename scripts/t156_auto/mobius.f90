SUBROUTINE VCOEF(W,ETAP,V,VP,VPP)
  IMPLICIT NONE
  DOUBLE PRECISION, INTENT(IN) :: W,ETAP
  DOUBLE PRECISION, INTENT(OUT) :: V,VP,VPP
  DOUBLE PRECISION Z,AT,N, VZ,VZZ
  Z=W*ETAP
  IF (ABS(Z).LT.1.D-3) THEN
    V=1.D0+Z**2/3.D0+Z**4/5.D0+Z**6/7.D0+Z**8/9.D0
    VZ=2.D0*Z/3.D0+4.D0*Z**3/5.D0+6.D0*Z**5/7.D0+8.D0*Z**7/9.D0
    VZZ=2.D0/3.D0+12.D0*Z**2/5.D0+30.D0*Z**4/7.D0+56.D0*Z**6/9.D0
  ELSE
    AT=0.5D0*LOG((1.D0+Z)/(1.D0-Z))
    N=Z/(1.D0-Z**2)-AT
    V=AT/Z
    VZ=N/Z**2
    VZZ=2.D0/(1.D0-Z**2)**2-2.D0*N/Z**3
  END IF
  VP=W*VZ
  VPP=W**2*VZZ
END SUBROUTINE VCOEF

SUBROUTINE BASE(S,W,KF,DEL,KAP,ETA,Q,M1,M3)
  IMPLICIT NONE
  DOUBLE PRECISION, INTENT(IN) :: S,W,KF,DEL
  DOUBLE PRECISION, INTENT(OUT) :: KAP,ETA,Q,M1,M3
  DOUBLE PRECISION PI,KP,ETAP,ETAPP,V,VP,VPP,A,P,PS
  PI=4.D0*ATAN(1.D0)
  KAP=0.20D0+0.30D0*SIN(S)+(KF-0.20D0)*S/PI
  KP=0.30D0*COS(S)+(KF-0.20D0)/PI
  ETA=1.80D0*(1.D0-DEL)/W*COS(S/2.D0)
  ETAP=-0.90D0*(1.D0-DEL)/W*SIN(S/2.D0)
  ETAPP=-0.45D0*(1.D0-DEL)/W*COS(S/2.D0)
  Q=ATANH(-0.90D0*SIN(S/2.D0))
  CALL VCOEF(W,ETAP,V,VP,VPP)
  A=1.D0+ETA**2
  P=KAP**2*A**2*VP
  PS=2.D0*KAP*KP*A**2*VP+4.D0*KAP**2*ETA*ETAP*A*VP+KAP**2*A**2*VPP*ETAPP
  M1=(4.D0*KAP**2*ETA*A*V-PS)/KAP
  M3=2.D0*KAP*A**2*V-ETA*M1
END SUBROUTINE BASE

SUBROUTINE MOMENT(S,W,KF,DEL,M2)
  IMPLICIT NONE
  DOUBLE PRECISION, INTENT(IN) :: S,W,KF,DEL
  DOUBLE PRECISION, INTENT(OUT) :: M2
  DOUBLE PRECISION H,KP,EP,QP,M1P,M3P,KM,EM,QM,M1M,M3M,K,ETA,Q,M1,M3
  H=1.D-4
  CALL BASE(S,W,KF,DEL,K,ETA,Q,M1,M3)
  IF (ABS(S).LT.1.D-12) THEN
    M2=0.D0
  ELSE
    CALL BASE(S+H,W,KF,DEL,KP,EP,QP,M1P,M3P)
    CALL BASE(S-H,W,KF,DEL,KM,EM,QM,M1M,M3M)
    M2=(M1P-M1M)/(2.D0*H*K)
  END IF
END SUBROUTINE MOMENT

SUBROUTINE FORCE2(S,W,KF,DEL,F2)
  IMPLICIT NONE
  DOUBLE PRECISION, INTENT(IN) :: S,W,KF,DEL
  DOUBLE PRECISION, INTENT(OUT) :: F2
  DOUBLE PRECISION H,K,ETA,Q,M1,M3,KP,EP,QP,M1P,M3P,KM,EM,QM,M1M,M3M,M2
  H=1.D-4
  CALL BASE(S,W,KF,DEL,K,ETA,Q,M1,M3)
  CALL MOMENT(S,W,KF,DEL,M2)
  IF (ABS(S).LT.1.D-12) THEN
    F2=0.D0
  ELSE
    CALL BASE(S+H,W,KF,DEL,KP,EP,QP,M1P,M3P)
    CALL BASE(S-H,W,KF,DEL,KM,EM,QM,M1M,M3M)
    F2=-(M3P-M3M)/(2.D0*H)-K*ETA*M2
  END IF
END SUBROUTINE FORCE2

SUBROUTINE FORCE3(S,W,KF,DEL,F3)
  IMPLICIT NONE
  DOUBLE PRECISION, INTENT(IN) :: S,W,KF,DEL
  DOUBLE PRECISION, INTENT(OUT) :: F3
  DOUBLE PRECISION H,K,ETA,Q,M1,M3,M2,MP,MM
  H=1.D-4
  CALL BASE(S,W,KF,DEL,K,ETA,Q,M1,M3)
  CALL MOMENT(S,W,KF,DEL,M2)
  CALL MOMENT(S+H,W,KF,DEL,MP)
  CALL MOMENT(S-H,W,KF,DEL,MM)
  F3=(MP-MM)/(2.D0*H)+K*M1-K*ETA*M3
END SUBROUTINE FORCE3

SUBROUTINE SEED(S,W,KF,DEL,F1,F2,F3,M1,M2,M3,KAP,ETA,Q)
  IMPLICIT NONE
  DOUBLE PRECISION, INTENT(IN) :: S,W,KF,DEL
  DOUBLE PRECISION, INTENT(OUT) :: F1,F2,F3,M1,M2,M3,KAP,ETA,Q
  DOUBLE PRECISION H,KP,EP,QP,M1P,M3P,KM,EM,QM,M1M,M3M,F2P,F2M
  H=1.D-4
  CALL BASE(S,W,KF,DEL,KAP,ETA,Q,M1,M3)
  CALL MOMENT(S,W,KF,DEL,M2)
  CALL FORCE2(S,W,KF,DEL,F2)
  CALL FORCE3(S,W,KF,DEL,F3)
  CALL FORCE2(S+H,W,KF,DEL,F2P)
  CALL FORCE2(S-H,W,KF,DEL,F2M)
  F1=(KAP*ETA*F3-(F2P-F2M)/(2.D0*H))/KAP
END SUBROUTINE SEED
