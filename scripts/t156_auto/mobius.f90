! T156: finite-width symmetric Mobius-strip BVP.
! Equations (23)-(29) of Starostin & van der Heijden (2015).
! The constitutive-consistent endpoint sign follows Eqs. (20)-(21);
! the printed Eq. (39) has the opposite sign on the curvature term.
SUBROUTINE FUNC(NDIM,U,ICP,PAR,IJAC,F,DFDU,DFDP)
  IMPLICIT NONE
  INTEGER, INTENT(IN) :: NDIM, IJAC, ICP(*)
  DOUBLE PRECISION, INTENT(IN) :: U(NDIM), PAR(*)
  DOUBLE PRECISION, INTENT(OUT) :: F(NDIM)
  DOUBLE PRECISION, INTENT(INOUT) :: DFDU(NDIM,*), DFDP(NDIM,*)
  DOUBLE PRECISION PI,W,KF,DEL
  DOUBLE PRECISION F1,F2,F3,M1,M2,M3,KAP,ETA,Q,PSI,THETA,PHI
  DOUBLE PRECISION ETAP,ZEXP,TQ,SECH2,ZETA
  DOUBLE PRECISION V,VP,VPP,A1,A2,A3,A4,B2,B3,B4
  DOUBLE PRECISION ONEETA,DENK,DENETA,KP,ETAPP,QP
  PI=4.D0*ATAN(1.D0)
  W=PAR(1)
  KF=PAR(2)
  DEL=PAR(3)
  F1=U(1); F2=U(2); F3=U(3)
  M1=U(4); M2=U(5); M3=U(6)
  KAP=U(7); ETA=U(8); Q=U(9)
  PSI=U(10); THETA=U(11); PHI=U(12)
  ZEXP=EXP(-2.D0*MIN(ABS(Q),350.D0))
  TQ=SIGN(1.D0,Q)*(1.D0-ZEXP)/(1.D0+ZEXP)
  SECH2=4.D0*ZEXP/(1.D0+ZEXP)**2
  ZETA=(1.D0-DEL)*TQ
  ETAP=ZETA/W
  CALL VCOEF(W,ETAP,V,VP,VPP)
  ONEETA=1.D0+ETA**2
  A1=0.25D0*(2.D0*VP**2-V*VPP)
  A2=V+ETAP*VP
  A3=V*A2
  A4=VP
  B2=0.5D0*(ETAP*(VP**2-V*VPP)-V*VP)
  B3=0.5D0*(2.D0*VP+ETAP*VPP)
  B4=0.5D0*VPP
  DENK=4.D0*A1*ONEETA**2
  DENETA=DENK*KAP
  KP=(-B3*M1+B4*F2-8.D0*B2*KAP*ETA*ONEETA)/DENK
  ETAPP=(A2*M1-A4*F2-4.D0*A3*KAP*ETA*ONEETA)/DENETA
  QP=W*ETAPP/((1.D0-DEL)*SECH2)
  F(1)=PI*KAP*F2
  F(2)=PI*(-KAP*F1+KAP*ETA*F3)
  F(3)=PI*(-KAP*ETA*F2)
  F(4)=PI*KAP*M2
  F(5)=PI*(-KAP*M1+KAP*ETA*M3+F3)
  F(6)=PI*(-KAP*ETA*M2-F2)
  F(7)=PI*KP
  F(8)=PI*ETAP
  F(9)=PI*QP
  F(10)=PI*KAP*SIN(PHI)/SIN(THETA)
  F(11)=PI*KAP*COS(PHI)
  F(12)=PI*KAP*(ETA-SIN(PHI)*COS(THETA)/SIN(THETA))
  F(13)=PI*SIN(THETA)*COS(PSI)
  F(14)=PI*SIN(THETA)*SIN(PSI)
  F(15)=PI*COS(THETA)
END SUBROUTINE FUNC

SUBROUTINE STPNT(NDIM,U,PAR,T)
  IMPLICIT NONE
  INTEGER, INTENT(IN) :: NDIM
  DOUBLE PRECISION, INTENT(INOUT) :: U(NDIM),PAR(*)
  DOUBLE PRECISION, INTENT(IN) :: T
  DOUBLE PRECISION PI,S,W,KF,DEL
  DOUBLE PRECISION F1,F2,F3,M1,M2,M3,KAP,ETA,Q
  PAR(1)=3.D0*SQRT(3.D0)/4.D0
  PAR(2)=5.D-2
  PAR(3)=1.D-4
  PI=4.D0*ATAN(1.D0)
  S=PI*T
  W=PAR(1); KF=PAR(2); DEL=PAR(3)
  CALL SEED(S,W,KF,DEL,F1,F2,F3,M1,M2,M3,KAP,ETA,Q)
  U(1)=F1; U(2)=F2; U(3)=F3
  U(4)=M1; U(5)=M2; U(6)=M3
  U(7)=KAP; U(8)=ETA; U(9)=Q
  U(10)=PI+S
  U(11)=PI/2.D0
  U(12)=PI/2.D0+S/2.D0
  U(13)=-SIN(S)
  U(14)=COS(S)-1.D0
  U(15)=0.D0
END SUBROUTINE STPNT

SUBROUTINE BCND(NDIM,PAR,ICP,NBC,U0,U1,FB,IJAC,DBC)
  IMPLICIT NONE
  INTEGER, INTENT(IN) :: NDIM,ICP(*),NBC,IJAC
  DOUBLE PRECISION, INTENT(IN) :: PAR(*),U0(NDIM),U1(NDIM)
  DOUBLE PRECISION, INTENT(OUT) :: FB(NBC)
  DOUBLE PRECISION, INTENT(INOUT) :: DBC(NBC,*)
  DOUBLE PRECISION PI
  PI=4.D0*ATAN(1.D0)
  FB(1)=U0(2)
  FB(2)=U0(5)
  FB(3)=U1(7)-PAR(2)
  FB(4)=U0(9)
  FB(5)=U0(10)-PI
  FB(6)=U1(10)-2.D0*PI
  FB(7)=U1(11)-PI/2.D0
  FB(8)=U0(12)-PI/2.D0
  FB(9)=U1(12)-PI
  FB(10)=U0(13)
  FB(11)=U1(13)
  FB(12)=U0(14)
  FB(13)=U0(15)
  FB(14)=U1(15)
  ! Constitutive-consistent Eq. (21) endpoint:
  FB(15)=U0(6)+U0(8)*U0(4)-2.D0*U0(7)*(1.D0+U0(8)**2)**2
END SUBROUTINE BCND

SUBROUTINE ICND(NDIM,PAR,ICP,NINT,U,UOLD,UDOT,UPOLD,FI,IJAC,DINT)
  IMPLICIT NONE
  INTEGER, INTENT(IN) :: NDIM,ICP(*),NINT,IJAC
  DOUBLE PRECISION, INTENT(IN) :: PAR(*),U(NDIM),UOLD(NDIM),UDOT(NDIM),UPOLD(NDIM)
  DOUBLE PRECISION, INTENT(OUT) :: FI(NINT)
  DOUBLE PRECISION, INTENT(INOUT) :: DINT(NINT,*)
  IF (NINT.GT.0) FI=0.D0
END SUBROUTINE ICND

